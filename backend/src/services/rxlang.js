/** t('Date') in [lang]; English (or the key) when there's no entry. */
const translator = (lang) => (s) => (lang !== 'en' && L[lang]?.[s]) || s;

const NAMES = { bn: 'Bengali', hi: 'Hindi' };

const sha = (x) => crypto.createHash('sha1').update(JSON.stringify(x)).digest('hex');

/**
 * The doctor's own words in [lang]: { complaint, advice, instructions[], cautions[] }.
 * Cached on the prescription (rx.localized[lang].text) until the wording changes.
 * With AI off or on error the English stays (labels are still translated).
 */
async function freeText(rx, complaint, lang) {
  const source = {
    complaint: complaint || '',
    advice: String(rx.advice || ''),
    instructions: (rx.items || []).map((i) => i.instructions || ''),
    cautions: (rx.items || []).map((i) => i.caution || ''),
  };
  const english = { ...source, hash: sha(source), translated: false };
  if (lang === 'en') return english;
  const cached = rx.localized?.[lang]?.text;
  if (cached?.hash === english.hash && cached.translated) return cached;
  const empty = !source.complaint && !source.advice && !source.instructions.some(Boolean) && !source.cautions.some(Boolean);
  if (empty || !ai.enabled()) return english;
  try {
    const out = await Promise.race([
      ai.completeJson({
        effort: 'low',
        maxTokens: 2000,
        schema: {
          type: 'object',
          properties: {
            complaint: { type: 'string' }, advice: { type: 'string' },
            instructions: { type: 'array', items: { type: 'string' } }, cautions: { type: 'array', items: { type: 'string' } },
          },
          required: ['complaint', 'advice', 'instructions', 'cautions'],
          additionalProperties: false,
        },
        system: [
          `Translate a doctor's prescription notes from English into simple, everyday ${NAMES[lang]} (${NAMES[lang]} script) for a patient in India.`,
          'Translate meaning exactly. Do not add, remove, soften or change any medical instruction, number, dose, time or warning.',
          'Keep medicine names, test names and units (mg, mcg, ml, mmHg) in English as written. Keep numbers as digits.',
          'Keep each list item in the same position; an empty item stays empty. Keep line breaks in the advice.',
        ].join('\n'),
        messages: [{ role: 'user', content: JSON.stringify(source) }],
      }),
      new Promise((resolve) => setTimeout(() => resolve(null), 20000)),
    ]);
    const d = out?.data;
    const sameShape = d && Array.isArray(d.instructions) && d.instructions.length === source.instructions.length && Array.isArray(d.cautions) && d.cautions.length === source.cautions.length;
    if (!sameShape) return english;
    // An empty English field stays empty; a filled one never becomes empty.
    const keep = (en, tr) => (en ? String(tr || '').trim() || en : '');
    return {
      complaint: keep(source.complaint, d.complaint),
      advice: keep(source.advice, d.advice),
      instructions: source.instructions.map((en, i) => keep(en, d.instructions[i])),
      cautions: source.cautions.map((en, i) => keep(en, d.cautions[i])),
      hash: english.hash,
      translated: true,
    };
  } catch (err) {
    console.warn('[rxlang]', err.message);
    return english;
  }
}

